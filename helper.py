from aiogram import F, types
from aiogram.filters import Command
from config import dp

HELP_TEXT = """📖 <b>راهنمای استفاده از ربات PowerNetwork</b>

برای ورود کامل به مجموعه، این مراحل را به ترتیب انجام بده:

1️⃣ <b>شروع ربات</b>
دستور /start را بزن. ربات خوش‌آمد می‌گوید و ویدیوی اول را برایت می‌فرستد.

2️⃣ <b>دیدن ویدیوها</b>
ویدیوی اول را کامل ببین و زیرش روی «✅ ویدیو را دیدم» بزن تا ویدیوی دوم ارسال شود. ویدیوی دوم را هم کامل ببین و دوباره روی «✅ ویدیو را دیدم» بزن.

3️⃣ <b>ثبت نام و تکمیل فرم</b>
بعد از ویدیوها دکمه‌های «ثبت نام» و «عضویت در گروه» برایت باز می‌شود. اول روی «ثبت نام» بزن و به 8 سؤال پاسخ بده:
• نام و نام خانوادگی
• شهر محل زندگی
• تخصص و مهارت‌ها
• زمینه‌های فعالیت
• کمکی که می‌توانی به شبکه ارائه بدهی
• کمکی که نیاز داری
• راه ارتباطی (شماره تماس 11 رقمی، ایمیل یا آیدی تلگرام با @)
• توضیحات بیشتر (اگر ندارید بنویس «ندارم»)
پاسخ‌ها را فقط به‌صورت متن بفرست.

4️⃣ <b>بعد از تکمیل فرم</b>
خلاصه فرمت نمایش داده می‌شود و یک پیام صوتی خوش‌آمدگویی برایت ارسال می‌شود. معرفی تو (به‌جز آیدی عددی) در تاپیک «معرفی اعضا» و نام و راه ارتباطی‌ات در تاپیک «شبکه سازی» گروه منتشر می‌شود، پس فقط چیزی بنویس که راحت هستی دیگران ببینند.

5️⃣ <b>عضویت در گروه</b>
بعد از ثبت نام روی «عضویت در گروه» بزن تا لینک ورود به گروه برایت ارسال شود.

6️⃣ <b>اقدام برای کوچ</b>
روی «اقدام برای کوچ» بزن. درخواستت ثبت می‌شود و بعد از بررسی ادمین، یک کوچ مجموعه برایت مشخص می‌شود. منتظر پیام کوچ باش.

❓ <b>مشکل داری؟</b>
• ویدیو نیامد؟ دستور /start را دوباره بزن.
• دکمه «ثبت نام» را نمی‌بینی؟ ویدیوها را تا آخر ببین و روی «ویدیو را دیدم» بزن، یا /start را بفرست.
• اشتباهی در فرم ثبت کردی؟ به ادمین مجموعه اطلاع بده.
• هر وقت خواستی این راهنما را دوباره ببینی، روی «راهنما» بزن یا /help را بفرست."""


@dp.message(Command("help"))
@dp.message(F.text == "راهنما")
async def send_help(message: types.Message):
    await message.answer(HELP_TEXT, parse_mode="HTML")
